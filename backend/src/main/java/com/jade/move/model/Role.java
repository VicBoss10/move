package com.jade.move.model;

/**
 * User role enumeration.
 *
 * <p>Represents the authorization role for users:</p>
 * <ul>
 *   <li>ADMIN: Administrator with full system access</li>
 *   <li>USER: Standard user with limited access</li>
 * </ul>
 *
 * @since 0.0.1
 */
public enum Role {
    ADMIN,
    USER
}
