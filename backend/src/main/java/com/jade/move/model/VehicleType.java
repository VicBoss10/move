package com.jade.move.model;

/**
 * Vehicle type enumeration.
 *
 * <p>Represents the classification of detected vehicles:</p>
 * <ul>
 *   <li>CAR: Passenger vehicle</li>
 *   <li>BUS: Multi-passenger transport</li>
 *   <li>MOTORCYCLE: Two-wheeled motorized vehicle</li>
 *   <li>BICYCLE: Human-powered bicycle</li>
 *   <li>TRUCK: Heavy-duty cargo vehicle</li>
 * </ul>
 *
 * @since 0.0.1
 */
public enum VehicleType {
    CAR,
    BUS,
    MOTORCYCLE,
    BICYCLE,
    TRUCK
}
